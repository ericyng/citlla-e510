import AppKit
import SwiftUI

struct AboutView: View {
    @EnvironmentObject private var loginItem: LoginItemManager

    private var version: String {
        let short = Bundle.main.object(forInfoDictionaryKey: "CFBundleShortVersionString") as? String ?? "0.1.0"
        let build = Bundle.main.object(forInfoDictionaryKey: "CFBundleVersion") as? String ?? "1"
        return "\(short) (\(build))"
    }

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 18) {
                HStack(spacing: 16) {
                    Image(systemName: "computermouse.fill")
                        .font(.system(size: 52, weight: .medium))
                        .foregroundStyle(.tint)
                    VStack(alignment: .leading, spacing: 4) {
                        Text("Citlla E510").font(.largeTitle.bold())
                        Text("Version \(version)").font(.callout).foregroundStyle(.secondary)
                        Text("A macOS button remapper for the CITLLA PRO MAX E510 wireless mouse.")
                            .font(.callout)
                            .foregroundStyle(.secondary)
                    }
                }

                GroupBox("Device") {
                    VStack(alignment: .leading, spacing: 12) {
                        VStack(alignment: .leading, spacing: 6) {
                            Text("Supported receivers")
                                .font(.caption.weight(.semibold))
                                .foregroundStyle(.secondary)
                            ForEach(MouseReceiver.known) { receiver in
                                HStack(alignment: .firstTextBaseline, spacing: 12) {
                                    Text(receiver.name)
                                    Spacer(minLength: 12)
                                    Text(receiver.idDescription)
                                        .font(.callout)
                                        .monospaced()
                                        .foregroundStyle(.secondary)
                                }
                            }
                        }

                        Divider()

                        Grid(alignment: .leading, horizontalSpacing: 18, verticalSpacing: 8) {
                            GridRow {
                                Text("Buttons").foregroundStyle(.secondary)
                                Text("8 (HID Button page, report ID 2)")
                            }
                            GridRow {
                                Text("Extra interfaces").foregroundStyle(.secondary)
                                Text("Consumer Control + vendor page 0xFFB5")
                            }
                        }
                    }
                    .frame(maxWidth: .infinity, alignment: .leading)
                    .padding(.vertical, 4)
                }

                GroupBox("Startup") {
                    Toggle(
                        "Launch Citlla E510 at login",
                        isOn: Binding(
                            get: { loginItem.isEnabled },
                            set: { loginItem.setEnabled($0) }
                        )
                    )
                    if let error = loginItem.lastError {
                        Text(error)
                            .font(.caption)
                            .foregroundStyle(.secondary)
                    }
                }

                GroupBox("How it works") {
                    Text("Citlla E510 installs a session event tap. When it sees a mouse button with a binding, it suppresses the original event and performs the action you chose. Events generated by the app itself are tagged so they are never remapped twice.")
                        .font(.callout)
                        .foregroundStyle(.secondary)
                        .fixedSize(horizontal: false, vertical: true)
                    Text("The event tap is system-wide: a binding applies to every mouse that reports the same button number, not only the CITLLA.")
                        .font(.caption)
                        .foregroundStyle(.tertiary)
                        .fixedSize(horizontal: false, vertical: true)
                        .padding(.top, 4)
                }

                Text("Made for macOS 15 or later. Not affiliated with CITLLA.")
                    .font(.caption)
                    .foregroundStyle(.tertiary)
            }
            .padding(24)
            .frame(maxWidth: .infinity, alignment: .leading)
        }
    }
}
